"use strict";
const fs = require("node:fs");
const path = require("node:path");

function expectedOutputs(root) {
  const core = fs.readFileSync(path.join(root, "lib/core.js"), "utf8");
  const commonJSAdapter = '  if (typeof module === "object" && module.exports) module.exports = api;\n  else root.SupereoHapticsCore = api;';
  if (!core.includes(commonJSAdapter)) throw new Error("Shared core adapter changed; update the browser-only generator explicitly.");
  // A runtime module is bundled by esbuild. Keep CommonJS module/exports out
  // so its validator is always published in this runtime's global context.
  const browserCore = core.replace(commonJSAdapter, "  root.SupereoHapticsCore = api;");
  const outputs = { "native/cordova-plugin-supereo-haptics/www/core.js": core };
  for (const [output, template] of [["addon/c3runtime/plugin.js", "addon/source/runtime-plugin.js"], ["addon/c3runtime/domSide.js", "addon/source/dom-handler.js"]]) {
    outputs[output] = "// Generated by tools/prepare-runtime.cjs from lib/core.js and " + template + ".\n" + browserCore + "\n" + fs.readFileSync(path.join(root, template), "utf8");
  }
  return outputs;
}

function prepareRuntime(root) {
  for (const [name, content] of Object.entries(expectedOutputs(root))) {
    fs.mkdirSync(path.dirname(path.join(root, name)), { recursive: true });
    fs.writeFileSync(path.join(root, name), content);
  }
}

module.exports = { expectedOutputs, prepareRuntime };
if (require.main === module) prepareRuntime(path.resolve(__dirname, ".."));
